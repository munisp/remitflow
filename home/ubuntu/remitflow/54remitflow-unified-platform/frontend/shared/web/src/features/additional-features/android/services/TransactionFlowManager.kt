package com.example.app.data.service

import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.withContext
import java.io.IOException
import java.util.UUID

// --- 1. Data Models and Enums ---

/**
 * Represents the status of a Know Your Customer (KYC) check.
 * This status is crucial for compliance before any transaction can proceed.
 */
enum class KycStatus {
    /** KYC process is currently under review. */
    PENDING,
    /** KYC has been successfully verified and approved. */
    APPROVED,
    /** KYC failed verification and the user is blocked from transactions. */
    REJECTED,
    /** KYC information is missing and must be provided. */
    REQUIRED
}

/**
 * Represents the data required to initiate a transaction.
 * All fields are mandatory for a valid transaction request.
 * @property amount The transaction amount, must be a positive value.
 * @property currency The three-letter ISO 4217 currency code (e.g., "USD", "EUR").
 * @property recipientId The unique identifier of the recipient account or user.
 * @property transactionType The category of the transaction (e.g., "TRANSFER", "PAYMENT", "WITHDRAWAL").
 * @property description An optional, brief description for the transaction.
 */
data class TransactionRequest(
    val amount: Double,
    val currency: String,
    val recipientId: String,
    val transactionType: String,
    val description: String? = null
)

/**
 * Represents the final result of a transaction attempt returned by the backend.
 * @property transactionId The unique ID of the initiated transaction, generated by the server.
 * @property status The final or intermediate status of the transaction (e.g., "PROCESSING", "COMPLETED", "FAILED").
 * @property message A human-readable message providing context on the transaction status.
 * @property timestamp The time the transaction was recorded on the server.
 */
data class TransactionResponse(
    val transactionId: String,
    val status: String,
    val message: String,
    val timestamp: Long = System.currentTimeMillis()
)

// --- 2. Custom Exceptions ---

/**
 * Base class for all custom exceptions in the transaction flow.
 */
sealed class TransactionException(message: String, cause: Throwable? = null) : Exception(message, cause)

/**
 * Thrown when a business rule is violated (e.g., insufficient funds, daily limit exceeded).
 * This is typically a 4xx error from the API that is not a network or server issue.
 */
class BusinessRuleException(message: String) : TransactionException(message)

/**
 * Thrown when the user's KYC status prevents the transaction from proceeding.
 */
class KycRequiredException(val kycStatus: KycStatus, message: String) : TransactionException(message)

/**
 * Thrown for general API errors that are not specific business rules (e.g., 5xx server errors).
 */
class ApiErrorException(message: String, cause: Throwable? = null) : TransactionException(message, cause)

/**
 * Thrown for network-related issues (e.g., no internet connection, timeout).
 */
class NetworkException(message: String, cause: Throwable? = null) : TransactionException(message, cause)

// --- 3. Standardized Result Wrappers ---

/**
 * A standardized result wrapper for the API layer, distinguishing between success and failure.
 */
sealed class ApiResult<out T : Any> {
    data class Success<out T : Any>(val data: T) : ApiResult<T>()
    data class Failure(val exception: TransactionException) : ApiResult<Nothing>()
}

/**
 * A standardized result wrapper for the Service layer, used to communicate status updates
 * and final results back to the UI via Kotlin Flow.
 */
sealed class ServiceResult<out T : Any> {
    /** Represents a successful operation or an intermediate status update. */
    data class Success<out T : Any>(val data: T) : ServiceResult<T>()
    /** Represents a final error that terminated the transaction flow. */
    data class Error(val exception: TransactionException, val userMessage: String) : ServiceResult<Nothing>()
    /** Represents an ongoing status update during the transaction process. */
    data class StatusUpdate(val status: String, val message: String) : ServiceResult<Nothing>()
}

// --- 4. API Interface and Mock Implementation ---

/**
 * Defines the contract for all backend interactions related to transactions and KYC.
 * In a production environment, this would be implemented by a library like Retrofit.
 */
interface TransactionApi {
    /**
     * Suspended function to asynchronously fetch the current KYC status.
     * @return An [ApiResult] containing the [KycStatus] on success, or a [TransactionException] on failure.
     */
    suspend fun getKycStatus(): ApiResult<KycStatus>

    /**
     * Suspended function to submit a transaction request to the server.
     * @param request The [TransactionRequest] data.
     * @return An [ApiResult] containing the [TransactionResponse] on success, or a [TransactionException] on failure.
     */
    suspend fun submitTransaction(request: TransactionRequest): ApiResult<TransactionResponse>
}

/**
 * Mock implementation of the [TransactionApi] for development and testing purposes.
 * Simulates network latency and various success/failure scenarios.
 */
class MockTransactionApi : TransactionApi {
    private val kycSimulationStatus = KycStatus.APPROVED // Change to PENDING, REJECTED, or REQUIRED for testing

    override suspend fun getKycStatus(): ApiResult<KycStatus> {
        delay(500) // Simulate network latency
        return try {
            when (kycSimulationStatus) {
                KycStatus.APPROVED -> ApiResult.Success(KycStatus.APPROVED)
