                KycStatus.REJECTED -> ApiResult.Success(KycStatus.REJECTED)
                KycStatus.REQUIRED -> ApiResult.Success(KycStatus.REQUIRED)
            }
        } catch (e: IOException) {
            ApiResult.Failure(NetworkException("Failed to connect to KYC service.", e))
        } catch (e: Exception) {
            ApiResult.Failure(ApiErrorException("Unknown error during KYC check.", e))
        }
    }

    override suspend fun submitTransaction(request: TransactionRequest): ApiResult<TransactionResponse> {
        delay(1000) // Simulate network latency
        return try {
            when {
                request.amount > 5000.0 -> {
                    // Simulate a business rule violation (e.g., daily limit)
                    ApiResult.Failure(BusinessRuleException("Transaction amount exceeds the maximum limit of 5000.0 ${request.currency}."))
                }
                request.amount < 1.0 -> {
                    // Simulate another business rule violation (e.g., minimum amount)
                    ApiResult.Failure(BusinessRuleException("Transaction amount is below the minimum required amount of 1.0 ${request.currency}."))
                }
                else -> {
                    // Simulate a successful transaction submission
                    ApiResult.Success(
                        TransactionResponse(
                            transactionId = "TXN-${UUID.randomUUID()}",
                            status = "PROCESSING",
                            message = "Transaction submitted successfully. Awaiting final confirmation from the ledger."
                        )
                    )
                }
            }
        } catch (e: IOException) {
            ApiResult.Failure(NetworkException("Transaction submission failed due to network error.", e))
        } catch (e: Exception) {
            ApiResult.Failure(ApiErrorException("Unknown error during transaction submission.", e))
        }
    }
}

// --- 5. Service Manager ---

/**
 * The core service manager responsible for orchestrating the entire transaction flow.
 * It handles input validation, KYC pre-checks, API communication, and error mapping.
 *
 * It utilizes Kotlin Coroutines and Flow to provide a modern, reactive, and
 * non-blocking interface for the Android application's ViewModel/Presenter layer.
 *
 * @property api The [TransactionApi] implementation for backend communication.
 * @property defaultDispatcher The [CoroutineDispatcher] to use for all background, blocking operations (e.g., Dispatchers.IO).
 */
class TransactionFlowManager(
    private val api: TransactionApi = MockTransactionApi(),
    private val defaultDispatcher: CoroutineDispatcher = Dispatchers.IO
) {

    /**
     * Orchestrates the transaction process, including automatic KYC checking and submission.
     *
     * The process emits a stream of [ServiceResult] updates to the collector:
     * 1. **Validation**: Checks for valid input parameters.
     * 2. **KYC Check**: Calls the API to verify the user's compliance status.
     * 3. **Submission**: If KYC is approved, the transaction is submitted.
     * 4. **Final Result**: Emits the final success or error state.
     *
     * @param request The [TransactionRequest] containing all necessary transaction details.
     * @return A [Flow] of [ServiceResult] providing real-time status updates and the final result.
     */
    fun initiateTransaction(request: TransactionRequest): Flow<ServiceResult<TransactionResponse>> = flow {
        // All heavy/suspending operations are executed within withContext(defaultDispatcher)
        withContext(defaultDispatcher) {
            // 1. Input Validation
            val validationError = validateRequest(request)
            if (validationError != null) {
                emit(validationError)
                return@withContext
            }

            // 2. KYC Status Check
            emit(ServiceResult.StatusUpdate("KYC_CHECKING", "Verifying user's compliance status..."))
            val kycStatusResult = api.getKycStatus()

            when (kycStatusResult) {
                is ApiResult.Success -> {
                    val kycStatus = kycStatusResult.data
                    if (kycStatus != KycStatus.APPROVED) {
                        handleKycFailure(kycStatus)
                        return@withContext
                    }
                }
                is ApiResult.Failure -> {
                    // Handle API layer failure during KYC check
                    emit(ServiceResult.Error(kycStatusResult.exception, "Failed to perform KYC check. Please try again."))
                    return@withContext
                }
            }

            // 3. Transaction Submission
            emit(ServiceResult.StatusUpdate("SUBMITTING", "KYC approved. Submitting transaction to the backend..."))
            val submissionResult = api.submitTransaction(request)

            when (submissionResult) {
                is ApiResult.Success -> {
                    // 4. Final Success
                    emit(ServiceResult.Success(submissionResult.data))
                }
                is ApiResult.Failure -> {
                    // Handle API layer failure during submission
                    val exception = submissionResult.exception
                    val userMessage = when (exception) {
                        is BusinessRuleException -> "Transaction failed: ${exception.message}"
                        is NetworkException -> "Connection error: Could not submit transaction. Check your internet."
                        else -> "An unexpected error occurred during submission."
                    }
                    emit(ServiceResult.Error(exception, userMessage))
                }
            }
        }
    }

    /**
     * Performs client-side validation of the [TransactionRequest].
     * @param request The request to validate.
     * @return A [ServiceResult.Error] if validation fails, or null if successful.
     */
    private fun validateRequest(request: TransactionRequest): ServiceResult.Error? {
        return when {
            request.amount <= 0.0 -> ServiceResult.Error(
                IllegalArgumentException("Amount must be positive."),
                "Invalid amount specified. Please enter a value greater than zero."
            )
            request.recipientId.isBlank() -> ServiceResult.Error(
                IllegalArgumentException("Recipient ID is missing."),
                "Recipient is required. Please select a valid recipient."
            )
            request.currency.length != 3 -> ServiceResult.Error(
                IllegalArgumentException("Invalid currency code."),
                "The currency code is invalid. Please use a 3-letter ISO code."
            )
            else -> null
        }
    }

    /**
     * Handles the scenario where the KYC status is not [KycStatus.APPROVED].
     * Emits a [ServiceResult.Error] with a specific [KycRequiredException].
     * @param kycStatus The non-approved KYC status.
     */
    private suspend fun handleKycFailure(kycStatus: KycStatus) {
        val message = when (kycStatus) {
            KycStatus.PENDING -> "KYC check is still pending. Please wait for approval."
            KycStatus.REJECTED -> "KYC check was rejected. You are blocked from initiating transactions."
            KycStatus.REQUIRED -> "KYC is required. Please complete your profile verification."
            KycStatus.APPROVED -> "KYC Approved (Should not happen here)" // Should not happen
        }
        emit(
            ServiceResult.Error(
                KycRequiredException(kycStatus, "Transaction blocked due to KYC status: $kycStatus"),
                message
            )
        )
    }

    /**
     * A utility function to demonstrate how the service can be used.
     * This is not part of the core service but useful for testing/example.
     */
    suspend fun runExample() {
        val exampleRequest = TransactionRequest(
            amount = 1500.0,
            currency = "EUR",
            recipientId = "user_456789",
            transactionType = "TRANSFER",
            description = "Monthly rent payment"
        )

        println("--- Starting Transaction Flow Example ---")
        initiateTransaction(exampleRequest).collect { result ->
            when (result) {
                is ServiceResult.Success -> {
                    val response = result.data
                    println("SUCCESS: Transaction ID: ${response.transactionId} | Status: ${response.status} | Message: ${response.message}")
                }
                is ServiceResult.Error -> {
                    println("ERROR: ${result.userMessage} | Details: ${result.exception.localizedMessage}")
                }
                is ServiceResult.StatusUpdate -> {
                    println("STATUS UPDATE: ${result.status} | Message: ${result.message}")
                }
            }
        }
        println("--- Transaction Flow Example Finished ---")
    }
}
